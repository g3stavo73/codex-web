
using System;
using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;
using CodexWeb.Api.Core.Entities;

namespace CodexWeb.Api.Core.Interfaces;

/// <summary>
/// Defines the operations available to the backend for controlling
/// the Codex runtime.
/// </summary>
public interface ICodexRuntime : IAsyncDisposable
{
    /// <summary>
    /// Initializes the runtime connection.
    /// Must be completed once before using the other operations.
    /// </summary>
    Task InitializeAsync(
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Creates a new Codex conversation thread.
    /// Returns the real thread ID generated by Codex.
    /// </summary>
    Task<string> CreateThreadAsync(
        string? workingDirectory = null,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Resumes an existing Codex thread.
    /// </summary>
    Task ResumeThreadAsync(
        string threadId,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Starts a new Codex turn inside an existing thread.
    /// Returns the real turn ID without waiting for the response to finish.
    /// </summary>
    Task<string> StartTurnAsync(
        string threadId,
        string prompt,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Requests interruption of an active Codex turn.
    /// The final interruption status must be confirmed through runtime events.
    /// </summary>
    Task InterruptTurnAsync(
        string threadId,
        string turnId,
        CancellationToken cancellationToken = default
    );

    /// <summary>
    /// Reads notifications received from the Codex runtime.
    /// This is a shared event stream and should have one central consumer.
    /// </summary>
    IAsyncEnumerable<CodexRuntimeEvent> ReadEventsAsync(
        CancellationToken cancellationToken = default
    );
}

/// <summary>
/// Base representation of an event emitted by the Codex runtime.
/// </summary>
public abstract record CodexRuntimeEvent(
    string ThreadId,
    string TurnId
);

/// <summary>
/// Represents a new text fragment received from Codex.
/// </summary>
public sealed record CodexMessageDeltaEvent(
    string ThreadId,
    string TurnId,
    string ItemId,
    string Delta
) : CodexRuntimeEvent(ThreadId, TurnId);

/// <summary>
/// Represents the final result of a Codex turn.
/// </summary>
public sealed record CodexTurnCompletedEvent(
    string ThreadId,
    string TurnId,
    CodexTaskStatus Status,
    string? ErrorMessage = null
) : CodexRuntimeEvent(ThreadId, TurnId);
